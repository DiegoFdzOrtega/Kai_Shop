insert into storage.buckets (id, name, public)
values ('imagenes', 'imagenes', true)
on conflict (id) do update set public = true;

drop policy if exists "imagenes lectura publica" on storage.objects;
create policy "imagenes lectura publica" on storage.objects
  for select using (bucket_id = 'imagenes');

drop policy if exists "imagenes subir admin" on storage.objects;
create policy "imagenes subir admin" on storage.objects
  for insert with check (bucket_id = 'imagenes' and public.es_admin());

drop policy if exists "imagenes editar admin" on storage.objects;
create policy "imagenes editar admin" on storage.objects
  for update using (bucket_id = 'imagenes' and public.es_admin());

drop policy if exists "imagenes borrar admin" on storage.objects;
create policy "imagenes borrar admin" on storage.objects
  for delete using (bucket_id = 'imagenes' and public.es_admin());
