-- ---------- Administradores ----------
-- Solo los usuarios que estén en esta tabla pueden editar.
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz default now()
);

create or replace function public.es_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

-- ---------- Productos ----------
create table if not exists public.productos (
  id          bigint generated by default as identity primary key,
  nombre      text not null,
  set_nombre  text not null default '',
  tipo        text not null default 'sobre'
              check (tipo in ('sobre','bundle','blister','etb','box','premium','tin','vintage')),
  img         text default '',
  stock       jsonb not null default '{}'::jsonb,   -- {"ES":5,"EN":3,"JP":0,"KR":0}
  tag         text default '',
  precio      text default '',
  c1          text default '#e5141b',
  c2          text default '#1e1e1e',
  orden       int  default 0,
  activo      boolean default true,
  created_at  timestamptz default now(),
  updated_at  timestamptz default now()
);

-- ---------- Gradeadas (Vault) ----------
create table if not exists public.gradeadas (
  id          bigint generated by default as identity primary key,
  nombre      text not null,
  set_nombre  text default '',
  anio        int,
  num         text default '',
  empresa     text default 'PSA',
  nota        numeric(3,1) default 10,
  etiqueta    text default 'GEM MT',
  tipo        text default 'fuego',      -- paleta de colores si no hay imagen
  carta       text default '',           -- imagen de la carta
  front       text default '',           -- foto real del slab (opcional)
  back        text default '',
  orden       int default 0,
  activo      boolean default true,
  created_at  timestamptz default now()
);

-- ---------- Eventos ----------
create table if not exists public.eventos (
  id      bigint generated by default as identity primary key,
  nombre  text not null,
  lugar   text default '',
  info    text default '',
  orden   int default 0
);

-- ---------- FAQ ----------
create table if not exists public.faq (
  id         bigint generated by default as identity primary key,
  pregunta   text not null,
  respuesta  text not null,
  orden      int default 0
);

-- ---------- Textos y ajustes ----------
create table if not exists public.ajustes (
  clave  text primary key,
  valor  text default ''
);

-- updated_at automático
create or replace function public.tocar_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;
drop trigger if exists productos_updated on public.productos;
create trigger productos_updated before update on public.productos
  for each row execute function public.tocar_updated_at();

-- =========================================================
--  SEGURIDAD (Row Level Security)
--  Cualquiera puede LEER (la web es pública).
--  Solo los admins pueden CREAR / EDITAR / BORRAR.
-- =========================================================
alter table public.admins    enable row level security;
alter table public.productos enable row level security;
alter table public.gradeadas enable row level security;
alter table public.eventos   enable row level security;
alter table public.faq       enable row level security;
alter table public.ajustes   enable row level security;

drop policy if exists "admins se ven a si mismos" on public.admins;
create policy "admins se ven a si mismos" on public.admins for select using (user_id = auth.uid());

do $$
declare t text;
begin
  foreach t in array array['productos','gradeadas','eventos','faq','ajustes'] loop
    execute format('drop policy if exists "lectura publica" on public.%I', t);
    execute format('create policy "lectura publica" on public.%I for select using (true)', t);
    execute format('drop policy if exists "escritura admin" on public.%I', t);
    execute format('create policy "escritura admin" on public.%I for all using (public.es_admin()) with check (public.es_admin())', t);
  end loop;
end $$;

-- Permisos de acceso a la API (RLS decide qué filas)
grant usage on schema public to anon, authenticated;
grant select on public.productos, public.gradeadas, public.eventos, public.faq, public.ajustes to anon, authenticated;
grant insert, update, delete on public.productos, public.gradeadas, public.eventos, public.faq, public.ajustes to authenticated;
grant select on public.admins to authenticated;
grant execute on function public.es_admin() to anon, authenticated;

